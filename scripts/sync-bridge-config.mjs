#!/usr/bin/env node
/**
 * Single source of truth: /bridge.config.json
 *
 * Syncs default bridge port into:
 * - packages/figma-agent-mcp/src/default-port.ts
 * - packages/figma-agent-plugin/src/shared/bridge-port.generated.ts
 * - packages/figma-agent-plugin/manifest.json (networkAccess.allowedDomains)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const configPath = resolve(root, "bridge.config.json");

const config = JSON.parse(readFileSync(configPath, "utf-8"));
const port = Number(config.defaultPort);

if (!Number.isInteger(port) || port < 1 || port > 65535) {
  console.error(
    `[sync-bridge-config] invalid defaultPort in bridge.config.json: ${config.defaultPort}`,
  );
  process.exit(1);
}

const wsOrigin = `ws://localhost:${port}`;

const mcpPortFile = resolve(
  root,
  "packages/figma-agent-mcp/src/default-port.ts",
);
writeFileSync(
  mcpPortFile,
  `/** Auto-generated by scripts/sync-bridge-config.mjs — do not edit. */\n` +
    `export const DEFAULT_BRIDGE_PORT = ${port};\n`,
);

const pluginPortFile = resolve(
  root,
  "packages/figma-agent-plugin/src/shared/bridge-port.generated.ts",
);
writeFileSync(
  pluginPortFile,
  `/** Auto-generated by scripts/sync-bridge-config.mjs — do not edit. */\n` +
    `export const DEFAULT_BRIDGE_PORT = ${port};\n`,
);

const manifestPath = resolve(
  root,
  "packages/figma-agent-plugin/manifest.json",
);
const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));
const domains = Array.isArray(manifest.networkAccess?.allowedDomains)
  ? [...manifest.networkAccess.allowedDomains]
  : [];

const nextDomains = domains
  .filter((d) => typeof d === "string" && !/^ws:\/\/localhost:\d+$/.test(d))
  .concat(wsOrigin);

manifest.networkAccess = {
  ...manifest.networkAccess,
  allowedDomains: nextDomains,
  reasoning: `Local MCP bridge (${wsOrigin}), GitHub release version checks (raw.githubusercontent.com), and default OpenAI-compatible API (api.openai.com). For other AI providers, add their host to allowedDomains in manifest.json and rebuild. Change the bridge port in /bridge.config.json then run pnpm sync:bridge (or any build).`,
};

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

console.error(
  `[sync-bridge-config] defaultPort=${port} → MCP default-port.ts, plugin bridge-port.generated.ts, manifest ${wsOrigin}`,
);
